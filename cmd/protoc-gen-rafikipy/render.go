// annotationOf renders the dataclass annotation for one field.
func annotationOf(f genField) string {
	switch {
	case strings.HasPrefix(f.kind, "list:"):
		inner := annotationForKind(strings.TrimPrefix(f.kind, "list:"))
		return fmt.Sprintf("list[%s] = dataclasses.field(default_factory=list)", inner)
	case strings.HasPrefix(f.kind, "map:"):
		inner := annotationForKind(strings.TrimPrefix(f.kind, "map:"))
		return fmt.Sprintf("dict[str, %s] = dataclasses.field(default_factory=dict)", inner)
	case f.presence:
		return fmt.Sprintf("Optional[%s] = None", annotationForKind(f.kind))
	default:
		return fmt.Sprintf("%s = %s", annotationForKind(f.kind), defaultOf(f))
	}
}

func annotationForKind(kind string) string {
	switch {
	case kind == "str":
		return "str"
	case kind == "bytes":
		return "bytes"
	case kind == "bool":
		return "bool"
	case kind == "int32" || kind == "int64":
		return "int"
	case kind == "float":
		return "float"
	case strings.HasPrefix(kind, "enum:"):
		return "str"
	case strings.HasPrefix(kind, "msg:"):
		return strings.TrimPrefix(kind, "msg:")
	default:
		return "object"
	}
}

// defaultOf renders the dataclass default for a plain (no-presence) field:
// the Python zero matching the proto zero.
func defaultOf(f genField) string {
	switch {
	case f.kind == "str":
		return `""`
	case strings.HasPrefix(f.kind, "enum:"):
		return `"` + strings.TrimPrefix(f.kind, "enum:") + `"`
	case f.kind == "bytes":
		return `b""`
	case f.kind == "bool":
		return "False"
	case f.kind == "int32" || f.kind == "int64":
		return "0"
	case f.kind == "float":
		return "0.0"
	default:
		return "None"
	}
}

// emitExpr renders the Python expression that turns a field value into its
// wire shape. name is the Python expression holding the value.
func emitExpr(f genField, name string) string {
	switch {
	case strings.HasPrefix(f.kind, "list:"):
		inner := strings.TrimPrefix(f.kind, "list:")
		return fmt.Sprintf("[%s for x in %s]", listElemExpr(inner, "x"), name)
	case strings.HasPrefix(f.kind, "map:"):
		inner := strings.TrimPrefix(f.kind, "map:")
		return fmt.Sprintf("dict((k, %s) for k, v in %s.items())", mapValueExpr(inner, "v"), name)
	case strings.HasPrefix(f.kind, "msg:"):
		return fmt.Sprintf("%s.to_dict()", name)
	case f.kind == "int64":
		return fmt.Sprintf("str(%s)", name)
	case f.kind == "float":
		return fmt.Sprintf("_float_out(%s)", name)
	case f.kind == "bytes":
		return fmt.Sprintf("_b64_out(%s)", name)
	default:
		return name
	}
}

func listElemExpr(kind, name string) string {
	if strings.HasPrefix(kind, "msg:") {
		return fmt.Sprintf("%s.to_dict()", name)
	}
	return encodeScalarExpr(kind, name)
}

func mapValueExpr(kind, name string) string {
	return encodeScalarExpr(kind, name)
}

func encodeScalarExpr(kind, name string) string {
	switch kind {
	case "int64":
		return fmt.Sprintf("str(%s)", name)
	case "float":
		return fmt.Sprintf("_float_out(%s)", name)
	case "bytes":
		return fmt.Sprintf("_b64_out(%s)", name)
	default:
		return name
	}
}

// decodeExpr renders the Python expression that turns a decoded JSON value
// into the field's Python value.
func decodeExpr(f genField, name string) string {
	switch {
	case strings.HasPrefix(f.kind, "list:"):
		inner := strings.TrimPrefix(f.kind, "list:")
		return fmt.Sprintf("[%s for x in %s]", listElemDecode(inner, "x"), name)
	case strings.HasPrefix(f.kind, "map:"):
		inner := strings.TrimPrefix(f.kind, "map:")
		return fmt.Sprintf("{k: %s for k, v in %s.items()}", mapValueDecode(inner, "v"), name)
	case strings.HasPrefix(f.kind, "msg:"):
		return fmt.Sprintf("%s.from_dict(%s)", strings.TrimPrefix(f.kind, "msg:"), name)
	case f.kind == "int32":
		return fmt.Sprintf("_int_in(%s)", name)
	case f.kind == "int64":
		return fmt.Sprintf("_int_in(%s)", name)
	case f.kind == "float":
		return fmt.Sprintf("_float_in(%s)", name)
	case f.kind == "bytes":
		return fmt.Sprintf("_b64_in(%s)", name)
	default:
		return name
	}
}

func listElemDecode(kind, name string) string {
	if strings.HasPrefix(kind, "msg:") {
		return fmt.Sprintf("%s.from_dict(%s)", strings.TrimPrefix(kind, "msg:"), name)
	}
	return decodeScalarExpr(kind, name)
}

func mapValueDecode(kind, name string) string {
	return decodeScalarExpr(kind, name)
}

func decodeScalarExpr(kind, name string) string {
	switch kind {
	case "int32", "int64":
		return fmt.Sprintf("_int_in(%s)", name)
	case "float":
		return fmt.Sprintf("_float_in(%s)", name)
	case "bytes":
		return fmt.Sprintf("_b64_in(%s)", name)
	default:
		return name
	}
}

// renderToDict emits to_dict: presence fields only when set, plain scalars
// only when non-zero, oneofs exactly one arm.
func renderToDict(b *strings.Builder, m *descriptorpb.DescriptorProto, path string, fields []genField, indent string) {
	fmt.Fprintf(b, "%s    def to_dict(self) -> dict:\n", indent)
	fmt.Fprintf(b, "%s        out = {}\n", indent)
	for _, f := range fields {
		switch {
		case f.oneof != "":
			// Emitted below, after a single set-arm check over the group.
		case strings.HasPrefix(f.kind, "list:"):
			fmt.Fprintf(b, "%s        if self.%s:\n%s            out[%q] = %s\n", indent, f.attr, indent, f.wire, emitExpr(f, "self."+f.attr))
		case strings.HasPrefix(f.kind, "map:"):
			fmt.Fprintf(b, "%s        if self.%s:\n%s            out[%q] = %s\n", indent, f.attr, indent, f.wire, emitExpr(f, "self."+f.attr))
		case f.presence:
			fmt.Fprintf(b, "%s        if self.%s is not None:\n%s            out[%q] = %s\n", indent, f.attr, indent, f.wire, emitExpr(f, "self."+f.attr))
		default:
			fmt.Fprintf(b, "%s        if self.%s != %s:\n%s            out[%q] = %s\n", indent, f.attr, defaultOf(f), indent, f.wire, emitExpr(f, "self."+f.attr))
		}
	}
	// Oneof groups: refuse two set arms rather than silently encoding one —
	// proto3's "setting one clears the others" has no dataclass equivalent,
	// and a silent pick would hide a caller bug.
	seen := map[string]bool{}
	for _, f := range fields {
		if f.oneof == "" || seen[f.oneof] {
			continue
		}
		seen[f.oneof] = true
		arms := make([]string, 0, 2)
		for _, g := range fields {
			if g.oneof == f.oneof {
				arms = append(arms, "self."+g.attr)
			}
		}
		fmt.Fprintf(b, "%s        _set_%s = [x for x in (%s) if x is not None]\n", indent, f.oneof, strings.Join(arms, ", "))
		fmt.Fprintf(b, "%s        if len(_set_%s) > 1:\n%s            raise ValueError(\"%s: at most one arm of oneof '%s' may be set\")\n", indent, f.oneof, indent, m.GetName(), f.oneof)
		for _, g := range fields {
			if g.oneof != f.oneof {
				continue
			}
			fmt.Fprintf(b, "%s        if self.%s is not None:\n%s            out[%q] = %s\n", indent, g.attr, indent, g.wire, emitExpr(g, "self."+g.attr))
		}
	}
	fmt.Fprintf(b, "%s        return out\n", indent)
}

// renderFromDict emits from_dict: per-field decode from the wire key,
// unknown keys ignored. The return annotation quotes the class path, which
// for nested classes is not yet bound when the module body executes — but
// annotations are strings under `from __future__ import annotations` and are
// never evaluated at import time.
func renderFromDict(b *strings.Builder, classPath string, fields []genField, indent string) {
	fmt.Fprintf(b, "%s    @classmethod\n", indent)
	fmt.Fprintf(b, "%s    def from_dict(cls, _d: dict) -> %q:\n", indent, classPath)
	fmt.Fprintf(b, "%s        obj = cls()\n", indent)
	for _, f := range fields {
		fmt.Fprintf(b, "%s        _v = _d.get(%q)\n", indent, f.wire)
		fmt.Fprintf(b, "%s        if _v is not None:\n%s            obj.%s = %s\n", indent, indent, f.attr, decodeExpr(f, "_v"))
	}
	fmt.Fprintf(b, "%s        return obj\n", indent)
}
